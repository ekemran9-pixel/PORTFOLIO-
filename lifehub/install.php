<?php
// One-time setup: writes config.php, creates tables and the admin account.

declare(strict_types=1);

define('APP_ROOT', __DIR__);
$configFile = APP_ROOT . '/config.php';

if (is_file($configFile)) {
    http_response_code(403);
    exit('LifeHub is already installed. Delete install.php from the server.');
}

$error = '';
$done = false;
$v = fn(string $k, string $d = '') => isset($_POST[$k]) && is_string($_POST[$k]) ? trim($_POST[$k]) : $d;

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $driver = $v('db_driver') === 'sqlite' ? 'sqlite' : 'mysql';
    $config = [
        'db_driver'    => $driver,
        'db_host'      => $v('db_host', 'localhost'),
        'db_name'      => $v('db_name'),
        'db_user'      => $v('db_user'),
        'db_pass'      => $_POST['db_pass'] ?? '',
        'default_lang' => $v('default_lang') === 'en' ? 'en' : 'bn',
        'timezone'     => 'Asia/Dhaka',
        'max_upload_mb' => 200,
        'debug'        => false,
    ];
    $username = $v('admin_user');
    $password = $_POST['admin_pass'] ?? '';

    try {
        if (!preg_match('/^[A-Za-z0-9_.-]{3,64}$/', $username)) {
            throw new RuntimeException('Username: 3-64 letters, numbers, _ . - only');
        }
        if (strlen($password) < 8) {
            throw new RuntimeException('Password must be at least 8 characters');
        }
        $opts = [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION];
        if ($driver === 'sqlite') {
            $pdo = new PDO('sqlite:' . APP_ROOT . '/data/lifehub.sqlite', null, null, $opts);
        } else {
            $dsn = sprintf('mysql:host=%s;dbname=%s;charset=utf8mb4', $config['db_host'], $config['db_name']);
            $pdo = new PDO($dsn, $config['db_user'], $config['db_pass'], $opts);
        }
        $schema = require APP_ROOT . '/inc/schema.php';
        foreach ($schema($driver) as $sql) {
            $pdo->exec($sql);
        }
        $st = $pdo->prepare('INSERT INTO users (username, password_hash, created_at) VALUES (?, ?, ?)');
        $st->execute([$username, password_hash($password, PASSWORD_DEFAULT), date('Y-m-d H:i:s')]);

        $php = "<?php\n// Generated by install.php. Keep this file private.\nreturn " . var_export($config, true) . ";\n";
        if (file_put_contents($configFile, $php) === false) {
            throw new RuntimeException('Could not write config.php — check folder permissions (755).');
        }
        @chmod($configFile, 0600);
        $done = true;
    } catch (Throwable $ex) {
        $error = $ex->getMessage();
    }
}
?>
<!doctype html>
<html lang="bn">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>LifeHub Setup</title>
<link href="https://fonts.googleapis.com/css2?family=Hind+Siliguri:wght@400;600&family=Inter:wght@400;600&display=swap" rel="stylesheet">
<link rel="stylesheet" href="assets/app.css">
</head>
<body>
<div class="auth-wrap">
  <div class="auth-card wide">
    <div class="auth-logo"><img src="assets/icon.svg" alt=""><h1>LifeHub Setup</h1></div>
    <?php if ($done): ?>
      <div class="flash flash-ok">✅ Installed! / ইনস্টল সম্পন্ন।</div>
      <p><strong>Important / জরুরি:</strong> cPanel File Manager থেকে <code>install.php</code> ফাইলটি এখনই delete করুন।</p>
      <a class="btn primary block" href="login.php">Login →</a>
    <?php else: ?>
      <?php if ($error): ?><div class="flash flash-err"><?= htmlspecialchars($error) ?></div><?php endif; ?>
      <form method="post" class="form">
        <h3>1. Database</h3>
        <label>Type
          <select name="db_driver" id="drv">
            <option value="mysql">MySQL (cPanel — recommended)</option>
            <option value="sqlite" <?= $v('db_driver') === 'sqlite' ? 'selected' : '' ?>>SQLite (no setup needed)</option>
          </select>
        </label>
        <div id="mysqlFields">
          <label>Host <input name="db_host" value="<?= htmlspecialchars($v('db_host', 'localhost')) ?>"></label>
          <label>Database name <input name="db_name" value="<?= htmlspecialchars($v('db_name')) ?>" placeholder="cpuser_lifehub"></label>
          <label>Database user <input name="db_user" value="<?= htmlspecialchars($v('db_user')) ?>" placeholder="cpuser_admin"></label>
          <label>Database password <input name="db_pass" type="password"></label>
        </div>
        <h3>2. Admin account</h3>
        <label>Username <input name="admin_user" required value="<?= htmlspecialchars($v('admin_user')) ?>"></label>
        <label>Password (8+) <input name="admin_pass" type="password" required minlength="8"></label>
        <label>Default language
          <select name="default_lang"><option value="bn">বাংলা</option><option value="en">English</option></select>
        </label>
        <button class="btn primary block">Install</button>
      </form>
      <script>
        const d = document.getElementById('drv'), f = document.getElementById('mysqlFields');
        const sync = () => f.style.display = d.value === 'mysql' ? '' : 'none';
        d.addEventListener('change', sync); sync();
      </script>
    <?php endif; ?>
  </div>
</div>
</body>
</html>
